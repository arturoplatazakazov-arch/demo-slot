def msgs(g):
    (slug, name, ref, theme, palette, logo, heroes, hp, lp, wild, scatter, bonus,
     frame, bgb, bgx, style) = g
    iso = "Neat grid, generous empty space between items, each isolated, same lighting, transparent background."
    letters = "" if "no letters" in lp else " Exactly 10, J, Q, K, A."
    one = ("Generate ONE single scene illustration only: {}. Tall portrait 9:16 picture for phones, same style and "
           "lighting as the backgrounds above. No logo, no symbols, no frame, no characters, no text, no collage. "
           "Keep a calmer area in the middle for the reels.")
    return [
        f'I\'m developing an original slot game called "{name}" and need all its art, one image per message, all in one consistent style. Concept: {theme} Palette: {palette}. Style for every image: {style}.\n\nImage 1 — the game LOGO: {logo}. Wide horizontal composition, isolated on a transparent background, no other text.',
        f"Image 2 — HIGH-PAY + SPECIAL SYMBOLS sheet (same style as the logo). Top row, 4 high-pay symbols: {'; '.join(hp)}. Bottom row, 3 specials: WILD — {wild}; SCATTER — {scatter}; BONUS — {bonus}. {iso}",
        f"Image 3 — LOW-PAY SYMBOLS sheet, one row of 5: {lp}.{letters} {iso}",
        f"Image 4 — CHARACTERS line-up, full body, side by side: {'; '.join(heroes)}. Generous empty space between them, each isolated, same lighting, transparent background.",
        f"Image 5 — REEL FRAME for a 5x3 slot grid: {frame}. Front view, symmetrical. Landscape 3:2 image and the frame FILLS the whole image edge to edge. Exact proportions: the empty inner window is 5 units wide by 3 units tall (aspect 1.67:1) and takes about 90% of the image width and 82% of the image height, so the borders are THIN (about 5% of the width each side). The window is an empty flat dark panel (no symbols, no reels). Ornaments only on the corners and the middle of the top and bottom. Transparent background outside the frame.",
        f"Image 5b — FRAME PARTS sheet for the same frame, to assemble a frame of any size (9-slice kit), same style, colours and border thickness: 1) the top-left CORNER piece; 2) a straight HORIZONTAL border segment that tiles seamlessly left-right (plain, no ornament); 3) a straight VERTICAL border segment that tiles seamlessly top-bottom (plain, no ornament); 4) the TOP-CENTER crest ornament; 5) the BOTTOM-CENTER ornament. Front view, each part isolated with generous empty space between them, transparent background.",
        f"Image 6 — BASE GAME BACKGROUND, wide 16:9 landscape, no UI, no text, no reels, no frame: {bgb}. Keep the centre calmer for the reels.",
        f"Image 7 — FREE SPINS BONUS BACKGROUND, wide 16:9, no UI, no text, no reels, no frame: {bgx}. More dramatic and festive than the base game, centre calmer for the reels.",
        "Image 8 — MOBILE BASE BACKGROUND. " + one.format(bgb),
        "Image 9 — MOBILE FREE SPINS BACKGROUND. " + one.format(bgx),
        'Image 10 — UI KIT sheet in exactly the same style as the logo: three win title banners with the text "BIG WIN", "MEGA WIN", "EPIC WIN" (each bigger and richer than the previous); a "FREE SPINS" title banner; a "BUY BONUS" button; an empty wide decorative plate for showing a number (no text on it); a round green check-mark button and a round red cross button. Neat grid, generous empty space between items, each isolated, transparent background.',
    ]


