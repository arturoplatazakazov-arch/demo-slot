def save(im: Image.Image, name: str, q: int = 88) -> None:
    path = V2 / name if not name.startswith("/") else name
    path.parent.mkdir(parents=True, exist_ok=True)
    if str(path).endswith(".jpg"):
        im.convert("RGB").save(path, "JPEG", quality=q, optimize=True, progressive=True)
    else:
        im.save(path, "WEBP", quality=q, method=6)
    print(f"  {path.relative_to(OUT)} {im.size[0]}x{im.size[1]}")


# ---------------------------------------------------------------- noise
def smooth_noise(h: int, w: int, scale: float, octaves: int = 4) -> np.ndarray:
    out = np.zeros((h, w), np.float32)
    amp, total = 1.0, 0.0
    for o in range(octaves):
        s = scale / (2 ** o)
        gh, gw = max(2, int(h / s) + 3), max(2, int(w / s) + 3)
        g = RNG.standard_normal((gh, gw)).astype(np.float32)
        g = np.asarray(Image.fromarray(g).resize((int(gw * s), int(gh * s)), Image.BICUBIC))[:h, :w]
        out += g * amp
        total += amp
        amp *= 0.5
    out /= total
    return (out - out.mean()) / (out.std() + 1e-6)


def marble_field(h: int, w: int, vein_scale: float = 1.0) -> np.ndarray:
    """RGB float marble: soft mottling + a few long turbulent veins."""
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    turb = smooth_noise(h, w, 180 * vein_scale, 5)
    mott = smooth_noise(h, w, 90 * vein_scale, 4)
    rgb = MARBLE[None, None, :] * (1 + 0.035 * mott[..., None])
    # main veins: diagonal sine bands bent by turbulence
    phase = (x * 0.9 + y * 0.45) / (260 * vein_scale) * 2 * math.pi + 2.6 * turb
    v = np.abs(np.sin(phase))
    vein = np.clip(1 - v, 0, 1) ** 16
    fine = np.clip(1 - np.abs(np.sin(phase * 2.7 + 1.7 * mott)), 0, 1) ** 30
    fade = 0.35 + 0.65 * np.clip(smooth_noise(h, w, 300 * vein_scale, 2) * 0.6 + 0.5, 0, 1)
    k = (vein * 0.55 + fine * 0.22) * fade
    rgb = rgb * (1 - k[..., None]) + VEIN[None, None, :] * k[..., None]
    # a thread of gold in the stone
    gphase = (x * 0.35 - y * 0.8) / (520 * vein_scale) * 2 * math.pi + 3.2 * turb
    gv = np.clip(1 - np.abs(np.sin(gphase)), 0, 1) ** 60 * 0.35
    rgb = rgb * (1 - gv[..., None]) + np.array([214, 170, 80], np.float32) * gv[..., None]
    return rgb


def bevel_shade(mask: np.ndarray, width: float, light=(-0.6, -0.8)) -> np.ndarray:
    """Directional shading of a raised edge: -1..1 (lit top-left)."""
    d = ndimage.distance_transform_edt(mask)
    hgt = np.clip(d / width, 0, 1)
    hgt = 1 - (1 - hgt) ** 2
    hgt = ndimage.gaussian_filter(hgt, 1.2)
    gy, gx = np.gradient(hgt)
    s = -(gx * light[0] + gy * light[1]) * width * 1.6
    return np.clip(s, -1, 1) * (d > 0)


def gold_fill(h: int, w: int, y0: float, y1: float) -> np.ndarray:
    """Vertical gold ramp (bright top, deep bottom) with a mid specular."""
    t = np.clip((np.arange(h, dtype=np.float32)[:, None] - y0) / max(1, y1 - y0), 0, 1)
    t = np.repeat(t, w, 1)
    a = np.where(t < 0.35, t / 0.35, 1.0)
    rgb = GOLD_HI * (1 - a[..., None]) + GOLD * a[..., None]
    b = np.clip((t - 0.55) / 0.45, 0, 1)
    rgb = rgb * (1 - b[..., None]) + GOLD_LO * b[..., None]
    return rgb


def to_img(rgb: np.ndarray, a: np.ndarray) -> Image.Image:
    arr = np.dstack([np.clip(rgb, 0, 255), np.clip(a, 0, 255)]).astype(np.uint8)
    return Image.fromarray(arr)


def ring(mask: np.ndarray, r0: float, r1: float, outside: bool = False) -> np.ndarray:
    d = ndimage.distance_transform_edt(~mask if outside else mask)
    return (d > r0) & (d <= r1)


