def step_sky() -> None:
    """Base sky = the FS sky graded to a pale dawn above the cloud sea; the
    bonus keeps the original saturated FS sky, so entering FS reads as the
    gods' storm breaking over the same dawn."""
    print("sky")
    for src, out, w in (("bg/sky_fs.jpg", "sky_dawn.jpg", 1920), ("bg/sky_fs_mob.jpg", "sky_dawn_mob.jpg", 1152)):
        im = Image.open(OUT / src).convert("RGB")
        a = np.asarray(im).astype(np.float32) / 255
        lum = (a * np.array([0.3, 0.59, 0.11])).sum(2, keepdims=True)
        g = a * 0.5 + lum * 0.5                    # half the purple
        g = 1 - (1 - g) ** 1.55                    # lift into daylight
        h = a.shape[0]
        yy = np.linspace(0, 1, h)[:, None, None]
        warm = np.array([1.05, 0.985, 0.92]) * (1 - yy) + np.array([0.98, 0.97, 1.0]) * yy
        g = g * warm
        # a cool haze over the lower third (distance) so the stele separates
        haze = np.clip((yy - 0.55) / 0.45, 0, 1) * 0.18
        g = g * (1 - haze) + np.array([0.80, 0.78, 0.86]) * haze
        save(Image.fromarray((np.clip(g, 0, 1) * 255).astype(np.uint8)), out, 86)


def step_clouds() -> None:
    """The storm below: a band of the cut storm clouds, tinted to the dawn
    (lavender body, warm rim). Two layers: back (behind Zeus) and front
    (between Zeus and the stele, hiding his waist)."""
    print("clouds")
    clouds = [Image.open(PARTS / f"cloud_{i}.png").convert("RGBA") for i in range(6)]

    def tint(c: Image.Image, dark: float) -> Image.Image:
        arr = np.asarray(c).astype(np.float32)
        lum = (arr[..., :3] * np.array([0.3, 0.59, 0.11])).sum(2, keepdims=True) / 255
        lo = np.array([70, 64, 100], np.float32)
        hi = np.array([250, 228, 210], np.float32)
        t = np.clip(lum * 1.9, 0, 1) ** 0.9
        rgb = lo * (1 - t) + hi * t
        rgb = rgb * (1 - dark)
        return to_img(rgb, arr[..., 3])

    def band(w: int, h: int, rows: list[tuple[float, float, float, int]], seed: int) -> Image.Image:
        rng = np.random.default_rng(seed)
        canvas = Image.new("RGBA", (w, h))
        for y_frac, scale, dark, count in rows:
            xs = np.linspace(-0.12, 1.02, count) + rng.uniform(-0.04, 0.04, count)
            for x in xs:
                c = clouds[int(rng.integers(0, 6))]
                if rng.random() < 0.5:
                    c = c.transpose(Image.FLIP_LEFT_RIGHT)
                s = scale * rng.uniform(0.85, 1.15) * w / 1920
                c = c.resize((max(1, int(c.width * s)), max(1, int(c.height * s))), Image.LANCZOS)
                c = tint(c, dark)
                canvas.alpha_composite(c, (int(x * w), int(y_frac * h - c.height / 2)))
        # fade the top edge so the band dissolves into the sky
        a = np.asarray(canvas).copy()
        ramp = np.clip(np.linspace(0, 1, h) / 0.35, 0, 1)[:, None]
        a[..., 3] = (a[..., 3] * ramp).astype(np.uint8)
        return Image.fromarray(a)

    save(band(1920, 560, [(0.35, 1.0, 0.05, 6), (0.62, 1.25, 0.18, 6), (0.88, 1.5, 0.32, 5)], 1), "clouds_back.webp", 80)
    save(band(1920, 420, [(0.55, 1.15, 0.12, 6), (0.85, 1.4, 0.3, 6)], 2), "clouds_front.webp", 80)
    save(band(1080, 640, [(0.35, 1.25, 0.05, 4), (0.62, 1.55, 0.18, 4), (0.88, 1.9, 0.32, 4)], 3), "clouds_back_mob.webp", 80)
    save(band(1080, 480, [(0.55, 1.4, 0.12, 4), (0.85, 1.8, 0.3, 4)], 4), "clouds_front_mob.webp", 80)


