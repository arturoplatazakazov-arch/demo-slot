def _palmette(width: int) -> Image.Image:
    corner_l, horiz, vert, palm = sheet("frame_kit", 4, thr=40, join=4)
    return palm.resize((width, round(width * palm.height / palm.width)), Image.LANCZOS)


def _meander(length: int, height: int) -> Image.Image:
    from olympus_thunder_build import _tile
    corner_l, horiz, vert, palm = sheet("frame_kit", 4, thr=40, join=4)
    horiz = horiz.resize((round(horiz.width * height / horiz.height), height), Image.LANCZOS)
    return _tile(horiz, length)


def _tablet(kind: str) -> None:
    g = TABLET[kind]
    bw, bh = g["board"]
    side, top, bottom, pad = g["side"], g["top"], g["bottom"], g["pad"]
    cov, ch = g["cornice"]
    pov, ph = g["plinth"]
    gable = g["gable"]
    palm_w = round(bw * 0.17)
    palm = _palmette(palm_w)
    palm_rise = round(palm.height * 0.5)         # how far the palmette stands above the apex

    # canvas coordinates
    W = bw + 2 * (side + cov) + 2 * pad
    body_x0 = pad + cov
    body_x1 = body_x0 + bw + 2 * side
    cornice_y1 = pad + palm_rise + gable + ch      # bottom of cornice = top of body
    board_x0, board_y0 = body_x0 + side, cornice_y1 + top
    body_y1 = board_y0 + bh + bottom
    plinth_y1 = body_y1 + ph
    H = plinth_y1 + pad
    yy, xx = np.mgrid[0:H, 0:W]

    body = (xx >= body_x0) & (xx < body_x1) & (yy >= cornice_y1) & (yy < body_y1)
    cornice = (xx >= pad) & (xx < W - pad) & (yy >= cornice_y1 - ch) & (yy < cornice_y1)
    plinth = (xx >= pad) & (xx < W - pad) & (yy >= body_y1) & (yy < plinth_y1)
    apex_y = cornice_y1 - ch - gable
    half = (W - 2 * pad) / 2 - 6
    cx = W / 2
    gable_m = (yy >= apex_y) & (yy < cornice_y1 - ch) & (np.abs(xx - cx) <= (yy - apex_y) / gable * half)
    hole = (xx >= board_x0) & (xx < board_x0 + bw) & (yy >= board_y0) & (yy < board_y0 + bh)

    parts = [gable_m, cornice, body, plinth]
    rgb = marble_field(H, W, 1.0 if kind == "desk" else 1.15)
    shade = np.zeros((H, W), np.float32)
    for m in parts:                      # each block bevelled on its own
        shade += bevel_shade(m, 9)
    # the gable's tympanum is recessed: darker interior with a lit lower lip
    tymp = gable_m & (ndimage.distance_transform_edt(gable_m) > 11)
    shade -= 0.22 * tymp
    rgb = rgb * (1 + 0.38 * shade[..., None])
    solid = (gable_m | cornice | body | plinth) & ~hole

    # gold trims: fillet along the cornice / plinth joints, a fine rule inset
    # on the body, and the rim of the well.
    gold = gold_fill(H, W, 0, H)
    rim = ring(hole, 0, 6, outside=True) & solid
    rule = ring(body, 13, 16) & ~ndimage.binary_dilation(hole, iterations=12)
    joints = ((np.abs(yy - cornice_y1) <= 2) | (np.abs(yy - body_y1) <= 2)) & solid
    gold_m = rim | rule | joints
    # per-trim local ramp so thin lines still read as metal
    local = ndimage.gaussian_filter(ring(hole, 0, 6, outside=True).astype(np.float32), 1.5)
    gtone = gold * (0.85 + 0.3 * local[..., None])
    rgb = np.where(gold_m[..., None], gtone, rgb)
    # dark hairline between rim and well, and under the rim (depth)
    hair = ring(hole, 0, 1.5, outside=True)
    rgb = np.where(hair[..., None], np.array([40, 26, 8], np.float32), rgb)
    # the well casts ambient occlusion onto the marble just outside the rim
    ao = ring(hole, 6, 22, outside=True) & solid
    d_out = ndimage.distance_transform_edt(~hole)
    rgb = rgb * np.where(ao, 0.86 + 0.14 * np.clip((d_out - 6) / 16, 0, 1), 1.0)[..., None]

    a = solid.astype(np.float32) * 255
    a = ndimage.gaussian_filter(a, 0.6) * solid + 0 * a
    img = to_img(rgb, a)

    # meander friezes on the cornice and plinth faces
    fr_h = ch - 6
    fr = _meander(W - 2 * pad - 24, fr_h)
    img.alpha_composite(fr, (pad + 12, cornice_y1 - ch + 3))
    fr2 = _meander(W - 2 * pad - 24, ph - 8)
    img.alpha_composite(fr2, (pad + 12, body_y1 + 4))

    # acroteria: palmette at the apex and halves at the gable ends
    img.alpha_composite(palm, (round(cx - palm.width / 2), apex_y - palm_rise))
    small = _palmette(round(palm_w * 0.55))
    img.alpha_composite(small, (pad - 2, cornice_y1 - ch - round(small.height * 0.72)))
    img.alpha_composite(small.transpose(Image.FLIP_LEFT_RIGHT), (W - pad - small.width + 2, cornice_y1 - ch - round(small.height * 0.72)))

    # soft cast shadow (the stele floats; light from above-left)
    sh_a = ndimage.gaussian_filter((np.asarray(img)[..., 3] > 0).astype(np.float32), 14)
    sh_a = np.roll(np.roll(sh_a, 14, 0), 8, 1) * 120
    shadow = to_img(np.zeros((H, W, 3), np.float32) + np.array([16, 14, 40], np.float32), sh_a * ~hole)
    out = Image.alpha_composite(shadow, img)
    save(out, f"tablet_{kind}.webp", 90)
    print(f"    {kind}: frame {W}x{H}; board at ({board_x0},{board_y0}) -> css .board__frame left:-{board_x0}px top:-{board_y0}px")


