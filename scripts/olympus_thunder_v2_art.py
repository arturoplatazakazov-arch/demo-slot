def step_plaque() -> None:
    """9-slice marble plaque for CSS border-image (jackpots, FS counter):
    chamfered corners, bevel, gold rule inset. Slice = 36px."""
    print("plaque")
    W, H, c = 360, 160, 22
    yy, xx = np.mgrid[0:H, 0:W]
    pad = 6
    m = (xx >= pad) & (xx < W - pad) & (yy >= pad) & (yy < H - pad)
    for (px, py) in ((pad, pad), (W - pad, pad), (pad, H - pad), (W - pad, H - pad)):
        m &= (np.abs(xx - px) + np.abs(yy - py)) > c
    rgb = marble_field(H, W, 0.45)
    rgb = rgb * (1 + 0.34 * bevel_shade(m, 7)[..., None])
    gold = gold_fill(H, W, 0, H)
    edge = ring(m, 0, 3)
    rule = ring(m, 9, 11)
    rgb = np.where((edge | rule)[..., None], gold, rgb)
    a = ndimage.gaussian_filter(m.astype(np.float32), 0.5) * 255
    img = to_img(rgb, a)
    sh = ndimage.gaussian_filter(m.astype(np.float32), 3)
    sh = np.roll(sh, 3, 0) * 140
    out = Image.alpha_composite(to_img(np.zeros((H, W, 3)) + np.array([14, 12, 36]), sh), img)
    save(out, "plaque.webp", 90)


def _poly_mask(w: int, h: int, pts) -> np.ndarray:
    m = Image.new("L", (w, h))
    ImageDraw.Draw(m).polygon(pts, fill=255)
    return np.asarray(m) > 127


def step_ribbon() -> None:
    """Win counter: a marble banner whose swallowtail ends fold behind it,
    with a gold laurel sprig rising from each end (leaf from the FX sheet)."""
    print("ribbon")
    W, H = 760, 170
    bx0, bx1, by0, by1 = 130, W - 130, 40, 132
    marble = marble_field(H, W, 0.5)
    gold = gold_fill(H, W, by0, by1 + 20)
    img = Image.new("RGBA", (W, H))
    # tails: lower and outward, swallowtail notch at the outer end
    tail = _poly_mask(W, H, [(bx0 + 30, 64), (52, 64), (84, 106), (52, 150), (bx0 + 30, 150)])
    tails = tail | tail[:, ::-1]
    trgb = marble * 0.80 * (1 + 0.3 * bevel_shade(tails, 5)[..., None])
    trgb = np.where((ring(tails, 0, 3))[..., None], gold * 0.85, trgb)
    img.alpha_composite(to_img(trgb, tails * 255.0))
    # the fold: a dark triangle where the band turns under into the tail
    fold = _poly_mask(W, H, [(bx0, by1), (bx0 + 30, by1), (bx0 + 30, 150)])
    folds = fold | fold[:, ::-1]
    img.alpha_composite(to_img(np.zeros((H, W, 3)) + np.array([92, 86, 96]), folds * 255.0))
    band = np.zeros((H, W), bool)
    band[by0:by1, bx0:bx1] = True
    sh = ndimage.gaussian_filter(band.astype(np.float32), 6)
    img.alpha_composite(to_img(np.zeros((H, W, 3)) + np.array([20, 16, 40]), np.roll(sh, 5, 0) * 120 * ~band))
    rgb = marble * (1 + 0.32 * bevel_shade(band, 6)[..., None])
    rgb = np.where((ring(band, 0, 4) | ring(band, 9, 10.5))[..., None], gold, rgb)
    img.alpha_composite(to_img(rgb, band * 255.0))
    # laurel sprigs rising outward from the band ends
    leaf = trim(Image.open(PARTS / "fx_leaf.png").convert("RGBA"))
    lf = leaf.resize((112, round(112 * leaf.height / leaf.width)), Image.LANCZOS)
    left = trim(lf.transpose(Image.FLIP_LEFT_RIGHT).rotate(-12, expand=True, resample=Image.BICUBIC))
    if left.height > H - 4:
        left = left.resize((round(left.width * (H - 4) / left.height), H - 4), Image.LANCZOS)
    img.alpha_composite(left, (bx0 - left.width + 34, 2))
    right = left.transpose(Image.FLIP_LEFT_RIGHT)
    img.alpha_composite(right, (bx1 - 34, 2))
    save(img, "ribbon.webp", 90)
    print(f"    band {bx0},{by0}-{bx1},{by1} of {W}x{H}")


def step_gems() -> None:
    """Tier gems with their gold setting, cut from the left end of each v1
    jackpot plate (rhombus mask fitted to the setting)."""
    print("gems")
    x0, y0, x1, y1 = 0, 13, 86, 134       # setting bbox on the 365x146 plates
    for tier in ("grand", "major", "minor", "mini"):
        im = Image.open(OUT / f"ui/jp_{tier}.webp").convert("RGBA")
        sx = im.width / 365
        piece = im.crop((round(x0 * sx), round(y0 * sx), round(x1 * sx), round(y1 * sx)))
        w, h = piece.size
        yy, xx = np.mgrid[0:h, 0:w]
        dm = (np.abs(xx - w / 2) / (w / 2) + np.abs(yy - h / 2) / (h / 2)) <= 1.0
        pa = np.asarray(piece).copy()
        pa[..., 3] = (pa[..., 3] * ndimage.gaussian_filter(dm.astype(np.float32), 0.8)).astype(np.uint8)
        out = Image.fromarray(pa)
        save(out.resize((round(w * 96 / h), 96), Image.LANCZOS), f"gem_{tier}.webp", 90)


def step_cover() -> None:
    """720x720 catalog cover: dawn sky, cloud sea, Zeus mirrored on the right
    looking in (as in the game), logo across the lower left."""
    print("cover")
    S = 720
    sky = Image.open(V2 / "sky_dawn.jpg").convert("RGB")
    s = S / sky.height
    sky = sky.resize((round(sky.width * s), S), Image.LANCZOS)
    x0 = (sky.width - S) // 2 - 40
    canvas = sky.crop((x0, 0, x0 + S, S)).convert("RGBA")
    back = Image.open(V2 / "clouds_back.webp").convert("RGBA")
    back = back.resize((round(back.width * 0.6), round(back.height * 0.6)), Image.LANCZOS)
    canvas.alpha_composite(back, ((S - back.width) // 2, S - back.height + 30))
    zeus = Image.open(OUT / "zeus.webp").convert("RGBA").transpose(Image.FLIP_LEFT_RIGHT)
    zs = 660 / zeus.height
    zeus = zeus.resize((round(zeus.width * zs), 660), Image.LANCZOS)
    canvas.alpha_composite(zeus, (S - zeus.width + 18, 8))
    front = Image.open(V2 / "clouds_front.webp").convert("RGBA")
    front = front.resize((round(front.width * 0.55), round(front.height * 0.55)), Image.LANCZOS)
    canvas.alpha_composite(front, ((S - front.width) // 2 + 60, S - front.height + 40))
    logo = Image.open(OUT / "logo.webp").convert("RGBA")
    logo = logo.resize((480, round(logo.height * 480 / logo.width)), Image.LANCZOS)
    lx, ly = 18, S - logo.height - 22
    m = np.pad((np.asarray(logo)[..., 3] > 30).astype(np.float32), 60)
    bed = ndimage.gaussian_filter(m, 18)
    bed_img = to_img(np.zeros(bed.shape + (3,)) + np.array([11, 16, 38]), np.clip(bed * 1.4, 0, 1) * 190)
    tmp = Image.new("RGBA", (S + 240, S + 240))
    tmp.alpha_composite(bed_img, (lx - 60 + 120, ly - 60 + 6 + 120))
    canvas.alpha_composite(tmp.crop((120, 120, S + 120, S + 120)))
    canvas.alpha_composite(logo, (lx, ly))
