def plain(s):
    return s.replace('**', '')

def bold_words(s):
    """Words inside **...**, punctuation stripped the way gfx.body() matches them."""
    out, parts = [], s.split('**')
    for i, p in enumerate(parts):
        if i % 2: out += [w.strip(',.!') for w in p.split()]
    return out
