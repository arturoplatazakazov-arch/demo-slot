def page(var: str, meta: dict) -> str:
    h = (FRONT / "olympus-thunder.html").read_text()
    p = f"img/olympus-thunder/{var}/"
    h = re.sub(r"<title>.*?</title>", f"<title>{meta['title']}</title>", h)
    h = re.sub(r'(<link rel="stylesheet" href="css/olympus-thunder\.css\?v=\d+">)',
               lambda m: m.group(1) + f'\n<link rel="stylesheet" href="css/olympus-thunder-variants.css?v={CSS_V}">', h, count=1)
    body = (f'<body data-game-id="olympus-thunder" data-var="{var}" '
            f'data-sky="{var}/sky.jpg?v={ART_V}|{var}/sky_mob.jpg?v={ART_V}" data-sky-fs="{var}/sky_fs.jpg?v={ART_V}|{var}/sky_fs_mob.jpg?v={ART_V}" '
            f'data-temple="none" data-frame="{var}/frame.webp?v={ART_V}|{var}/frame.webp?v={ART_V}" '
            f'data-symbols="{p}symbols/" data-symbols-v="{ART_V}" data-titles="{p}titles/" data-cards="{p}ui/" data-hero="{var}/hero.webp?v={ART_V}" '
            f'data-spine-zeus="off" data-spine-logo="off" data-spine-symbols="off" data-spine-bg="off">')
    h = re.sub(r"<body[^>]*>", body, h, count=1)
    h = re.sub(r'<img class="zeus__glow"[^>]*>', "", h)
    for rel in ("logo.webp", "ui/jp_grand.webp", "ui/jp_major.webp", "ui/jp_minor.webp", "ui/jp_mini.webp",
                "ui/plate_win.webp", "ui/medallion.webp", "ui/buy_button.webp", "titles/jackpot.webp",
                "wheel/wheel.webp", "wheel/pointer.webp"):
        h = h.replace(f'img/olympus-thunder/{rel}"', f'{p}{rel}?v={ART_V}"')
    return h


def box(hole):
    x0, y0, x1, y1 = hole
    return f"left: {x0}%; top: {y0}%; right: {round(100 - x1, 1)}%; bottom: {round(100 - y1, 1)}%;"


