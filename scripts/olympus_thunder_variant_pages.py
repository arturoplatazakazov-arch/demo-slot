def main():
    layouts = {}
    for var in VARIANTS:
        lj = IMG / var / "layout.json"
        if not lj.exists():
            continue
        layouts[var] = json.loads(lj.read_text())
        html = page(var, VARIANTS[var])
        # group the plate texts so they can be centred inside the painted window
        html = html.replace('<span class="win-plate__label"', '<span class="win-plate__win"><span class="win-plate__label"', 1)
        html = re.sub(r'(<span class="win-plate__value"[^>]*></span>)', r"\1</span>", html, count=1)
        html = re.sub(r'(<span class="medallion__label">.*?</span>\s*<span class="medallion__value"[^>]*>.*?</span>)',
                      r'<span class="medallion__in">\1</span>', html, count=1, flags=re.S)
        html = re.sub(r'(<span class="buy-btn__label">.*?</span>)', r'<span class="buy-btn__in">\1</span>', html, count=1, flags=re.S)
        (FRONT / f"olympus-thunder-{var}.html").write_text(html)
        print("page", var)
    (FRONT / "css/olympus-thunder-variants.css").write_text(css(layouts))
    print("css", list(layouts))


if __name__ == "__main__":
    main()
